h.test("delivery callbacks preserve newer edits and do not consume a replacement draft", function()
  with_editor(function(f)
    h.truthy(codex.ask("Original request"))
    local ask = require("codex.ask")
    local draft = vim.api.nvim_get_current_buf()
    h.truthy(ask.submit())
    vim.bo[draft].modifiable = true
    vim.api.nvim_buf_set_lines(draft, 0, -1, false, { "Newer draft edits" })
    f.sends[1].opts.on_complete(true)
    h.eq({ "Newer draft edits" }, vim.api.nvim_buf_get_lines(draft, 0, -1, false))
    h.truthy(ask.submit())
    vim.cmd.bdelete({ args = { tostring(draft) }, bang = true })
    vim.api.nvim_set_current_buf(f.bufnr)
    h.truthy(codex.ask("Replacement request"))
    local replacement = vim.api.nvim_get_current_buf()
    f.sends[2].opts.on_complete(true)
    h.truthy(vim.api.nvim_buf_is_valid(replacement))
    h.contains(table.concat(vim.api.nvim_buf_get_lines(replacement, 0, -1, false), "\n"), "Replacement request")
  end)
end)

h.test("deleting a draft discards it and allows a fresh request", function()
