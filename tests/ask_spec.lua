h.test("ask actions and diagnostics use the source selection rather than the prompt buffer", function()
  with_editor(function(f)
    local namespace = vim.api.nvim_create_namespace("codex_ask_test")
    vim.diagnostic.set(namespace, f.bufnr, {
      { lnum = 0, col = 6, message = "first diagnostic", severity = vim.diagnostic.severity.ERROR },
      { lnum = 1, col = 6, message = "second diagnostic", severity = vim.diagnostic.severity.WARN },
    })
    h.truthy(codex.ask(nil, 2, 2))
    local ask = require("codex.ask")
    rawset(vim.ui, "select", function(items, _, callback)
      callback(items[3])
    end)
    ask.choose_action()
    h.eq(0, #f.sends)
    h.truthy(ask.add_diagnostics())
    h.truthy(ask.submit())
    local text = f.sends[1].text
    h.contains(text, "tests")
    h.contains(text, "second diagnostic")
    h.contains(text, "2:7")
    h.eq(nil, text:find("first diagnostic", 1, true))
    vim.diagnostic.reset(namespace, f.bufnr)
  end)
end)

h.test("ask submits edited context through the app-server backend", function()
