end)

h.test("diagnostics reject a changed source instead of applying stale selection lines", function()
  with_editor(function(f)
    h.truthy(codex.ask(nil, 2, 2))
    local draft = vim.api.nvim_get_current_buf()
    local before = vim.api.nvim_buf_get_lines(draft, 0, -1, false)
    vim.api.nvim_buf_set_lines(f.bufnr, 0, 0, false, { "new first line" })
    local namespace = vim.api.nvim_create_namespace("codex_ask_changed_test")
    vim.diagnostic.set(namespace, f.bufnr, {
      { lnum = 1, col = 0, message = "now on a different line", severity = vim.diagnostic.severity.WARN },
    })
    h.eq(false, require("codex.ask").add_diagnostics())
    h.eq(before, vim.api.nvim_buf_get_lines(draft, 0, -1, false))
    h.contains(table.concat(f.notifications, "\n"), "source changed")
    vim.diagnostic.reset(namespace, f.bufnr)
  end)
end)

h.test("ask window failures clean up without changing the editor", function()
  with_editor(function(f)
    local original_open = vim.api.nvim_open_win
    rawset(vim.api, "nvim_open_win", function()
      error("simulated window failure")
    end)
    local ok, result = pcall(codex.ask, "Explain")
    rawset(vim.api, "nvim_open_win", original_open)
    h.eq(true, ok)
    h.eq(false, result)
    h.eq(f.bufnr, vim.api.nvim_get_current_buf())
    h.eq(0, #f.sends)
    h.truthy(codex.ask("Try again"))
  end)
end)
