    f.sends[1].opts.on_complete(true)
    h.eq(false, vim.api.nvim_buf_is_valid(draft))
  end)
end)

h.test("follow-up keeps its draft when the conversation stops or changes", function()
  with_editor(function(f)
    h.eq(false, codex.follow_up())
    h.eq(f.bufnr, vim.api.nvim_get_current_buf())
    f.status = { backend = "app_server", running = true, jobid = 42, thread_id = "first", cwd = vim.fs.dirname(f.path) }
    h.truthy(codex.follow_up("Check the previous result"))
    local ask = require("codex.ask")
    local draft = vim.api.nvim_get_current_buf()
    f.status.thread_id = "second"
    h.eq(false, ask.submit())
    f.status.thread_id = "first"
    f.status.jobid = 43
    h.eq(false, ask.submit())
    f.status.jobid = 42
    f.status.running = false
    h.eq(false, ask.submit())
    h.eq(0, #f.sends)
    h.eq({ "Check the previous result" }, vim.api.nvim_buf_get_lines(draft, 0, -1, false))
    h.eq(true, vim.bo[draft].modifiable)
  end, "app_server")
end)

