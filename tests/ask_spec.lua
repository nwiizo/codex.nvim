local h = require("tests.harness")
local codex = require("codex")
local config = require("codex.config")

local function with_editor(callback, backend_name)
  backend_name = backend_name or "terminal"
  local module_name = backend_name == "terminal" and "codex.terminal" or "codex.app_server"
  local original_backend = package.loaded[module_name]
  local original_notify = vim.notify
  local original_select = vim.ui.select
  local original_buf = vim.api.nvim_get_current_buf()
  local directory = vim.fn.tempname()
  vim.fn.mkdir(directory, "p")
  directory = assert(vim.uv.fs_realpath(directory))
  local path = directory .. "/source.lua"
  vim.fn.writefile({ "local one = 1", "local two = 2" }, path)
  local bufnr = vim.fn.bufadd(path)
  vim.fn.bufload(bufnr)
  vim.api.nvim_set_current_buf(bufnr)
  vim.bo[bufnr].filetype = "lua"
  local fixture = {
    bufnr = bufnr,
    path = path,
    sends = {},
    notifications = {},
    status = { backend = backend_name, running = false, visible = false },
  }
  package.loaded[module_name] = {
    status = function()
      return vim.deepcopy(fixture.status)
    end,
    send = function(text, opts)
      table.insert(fixture.sends, { text = text, opts = opts })
      return true
    end,
  }
  rawset(vim, "notify", function(message)
    table.insert(fixture.notifications, message)
  end)
  config.setup({ backend = backend_name, cwd = "file" })
  local ok, err = xpcall(function()
    callback(fixture)
  end, debug.traceback)
  if package.loaded["codex.ask"] then
    require("codex.ask").reset()
  end
  rawset(vim, "notify", original_notify)
  rawset(vim.ui, "select", original_select)
  package.loaded[module_name] = original_backend
  vim.api.nvim_set_current_buf(original_buf)
  vim.api.nvim_buf_delete(bufnr, { force = true })
  vim.fn.delete(directory, "rf")
  if not ok then
    error(err, 0)
  end
end

h.test("request guidance follows input mode without becoming request text", function()
  with_editor(function(f)
    h.truthy(codex.ask())
    local ask = require("codex.ask")
    local function footer_text()
      return table.concat(vim.tbl_map(function(chunk)
        return chunk[1]
      end, vim.api.nvim_win_get_config(0).footer or {}))
    end
    local function header_text()
      return vim.api.nvim_eval_statusline(vim.wo.winbar, {
        winid = vim.api.nvim_get_current_win(),
        use_winbar = true,
        maxwidth = 24,
      }).str
    end
    h.contains(header_text(), "Ctrl-S")
    local insert_hint
    local insert_header
    vim.keymap.set("i", "<F8>", function()
      insert_hint = footer_text()
      insert_header = header_text()
    end, { buf = 0 })
    vim.api.nvim_feedkeys(vim.keycode("<Esc>i<F8>first line<CR>second line<Esc>"), "xt", false)
    h.contains(insert_hint, "Type your request")
    h.contains(insert_hint, "Ctrl-S")
    h.contains(insert_header, "Ctrl-S")
    h.contains(insert_hint, "Enter")
    h.contains(footer_text(), "Press i")
    h.contains(header_text(), "Ctrl-S")
    vim.cmd("normal! ggV")
    h.contains(footer_text(), "Press Esc")
    vim.api.nvim_feedkeys(vim.keycode("<Esc>"), "nx", false)
    h.eq(0, #f.sends)
    local text = table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), "\n")
    h.contains(text, "first line\nsecond line")
    h.eq(nil, text:find("Type your request", 1, true))
    h.truthy(ask.submit())
    h.eq(text, f.sends[1].text)
    h.truthy(codex.ask())
    h.contains(footer_text(), "queued")
    h.eq(nil, footer_text():find("Ctrl-S", 1, true))
    h.eq(nil, header_text():find("Ctrl-S", 1, true))
    f.sends[1].opts.on_complete(false)
    h.eq(true, vim.bo.modifiable)
    h.contains(footer_text(), "Ctrl-S")
    h.contains(header_text(), "Ctrl-S")
  end)
end)

h.test("ask keeps exact selected text until explicit submission", function()
  with_editor(function(f)
    vim.cmd("normal! gg06lvj2l")
    vim.api.nvim_feedkeys(vim.keycode("<Esc>"), "nx", false)
    h.truthy(codex.ask_visual("Explain this code"))
    local ask = require("codex.ask")
    local draft = vim.api.nvim_get_current_buf()
    h.eq("codex://ask", vim.api.nvim_buf_get_name(draft))
    h.eq(0, #f.sends)
    local text = table.concat(vim.api.nvim_buf_get_lines(draft, 0, -1, false), "\n")
    h.contains(text, "one = 1\nlocal two")
    h.eq(nil, text:find("local one", 1, true))
    vim.api.nvim_buf_set_lines(f.bufnr, 0, -1, false, { "changed after selection" })
    h.truthy(ask.submit())
    h.eq(1, #f.sends)
    h.contains(f.sends[1].text, "Explain this code")
    h.contains(f.sends[1].text, "one = 1\nlocal two")
    h.contains(f.sends[1].text, "@" .. f.path)
    h.eq(vim.fs.dirname(f.path), f.sends[1].opts.cwd)
    h.eq(true, f.sends[1].opts.submit)
    h.eq(false, vim.bo[draft].modifiable)
    h.eq(false, ask.submit())
    f.sends[1].opts.on_complete(true)
    h.eq(false, vim.api.nvim_buf_is_valid(draft))
    h.eq(f.bufnr, vim.api.nvim_get_current_buf())
  end)
end)

h.test("follow-up composes from the panel without attaching terminal output", function()
  with_editor(function(f)
    f.status = { backend = "terminal", running = true, jobid = 42, cwd = vim.fs.dirname(f.path) }
    vim.bo[f.bufnr].buftype = "nofile"
    h.truthy(codex.follow_up("Also explain the tradeoff"))
